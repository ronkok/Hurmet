// The color goes inside an attribute value, so keep it from closing the attribute.
const escapeColor = color => String(color).replace(/[&"<>]/g, "")

// The <pattern> markup for pattern `name`, with id `id`, drawn in `color`.
// `extraTransform` goes before the pattern's own transform; Sketch uses it to flip and
// scale its copies. Returns "" for an unknown name.
export const fillPatternDef = (name, id, color = "#000", extraTransform = "") => {
  const p = fillPatterns[name]
  if (!p) { return "" }
  const transform = `${extraTransform} ${p.transform || ""}`.trim()
  const content = color === "#000"
    ? p.content
    : p.content.replace(/"#000"/g, `"${escapeColor(color)}"`)
  return `<pattern id="${id}" width="${p.width}" height="${p.height}" ` +
    `patternUnits="userSpaceOnUse"${transform ? ` patternTransform="${transform}"` : ""}>` +
    `${content}</pattern>`
}

// The id of a pattern def in Hurmet's own SVG: one per pattern and color. Sketch's
// live drawing uses "fp-" ids, which it rescales on zoom, so Hurmet uses "hp-".
export const hurmetPatternId = (name, color) => `hp-${name}-${sanitizeForId(color)}`

// The defs for a Hurmet drawing's svg.patterns, a list of { name, color }.
// Patterns named in `omit` are left out.
export const patternDefs = (patterns, omit = []) => patterns
  .filter(p => !omit.includes(p.name))
  .map(p => fillPatternDef(p.name, hurmetPatternId(p.name, p.color), p.color))
  .join("")

// A fill pattern's apparent size on screen must stay constant as the
// drawing's scale/zoom S changes (see utils.redrawCanvas). The pattern's own
// transform, kept in data-base-transform, is preceded by scale(1/S).
export function setPatternScale(patternEl, S) {
  const baseTransform = patternEl.getAttribute('data-base-transform') || ''
  patternEl.setAttribute('patternTransform', `scale(${1 / S}) ${baseTransform}`.trim())
}

// Called from utils.redrawCanvas whenever S changes, to keep every
// already-created fill-pattern def in the live drawing (not shape
// thumbnails — see getCurrentScale in dwg.js) at a constant apparent size.
export function updateFillPatternScale(S) {
  const canvas = document.querySelector('.active-sketch')
  if (!canvas) return
  canvas.querySelectorAll('defs pattern[data-base-transform]').forEach(patternEl => {
    setPatternScale(patternEl, S)
  })
}
